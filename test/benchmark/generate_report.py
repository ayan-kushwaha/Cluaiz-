import os
import re
from collections import defaultdict

def generate_report():
    base_dir = r"C:\Users\Aryan\my\Cluaiz-workspace\cluaiz\test\benchmark"
    readme_path = os.path.join(base_dir, "README.mdx")
    
    # regex pattern
    pattern = re.compile(r'#### 🧠 Thinking Mode: (ON|OFF)\s*- \*\*Speed\*\*: ([\d\.]+) TPS\s*- \*\*TTFT\*\*: ([\d\.]+) s\s*- \*\*Tokens\*\*: (\d+)\s*- \*\*Time\*\*: ([\d\.]+) s')
    
    # hardware -> model -> tests -> list of modes
    # We want to group by Hardware first.
    hardware_data = defaultdict(list)
    
    for root, dirs, files in os.walk(base_dir):
        for f in files:
            if f.endswith('.md') and not f.startswith('README'):
                file_path = os.path.join(root, f)
                rel_path = os.path.relpath(file_path, base_dir)
                parts = rel_path.split(os.sep)
                
                # Assuming path like: GPU\NVIDIA_GeForce_...\model_name\test.md
                if len(parts) >= 4:
                    hardware_type = parts[0]
                    hardware_name = parts[1]
                    hardware_full = f"{hardware_type} - {hardware_name.replace('_', ' ')}"
                    model = parts[2]
                    test = parts[3].replace('.md', '')
                    
                    content = open(file_path, encoding='utf-8').read()
                    matches = pattern.findall(content)
                    
                    for m in matches:
                        mode = m[0]
                        speed = float(m[1])
                        ttft = float(m[2])
                        tokens = int(m[3])
                        time_s = float(m[4])
                        
                        hardware_data[hardware_full].append({
                            'model': model,
                            'test': test,
                            'mode': mode,
                            'speed': speed,
                            'ttft': ttft,
                            'tokens': tokens,
                            'time': time_s
                        })
                        
    output_mdx = []
    output_mdx.append("# 🚀 Cluaiz Universal Hardware Benchmark Report\n")
    output_mdx.append("This file is automatically generated by the benchmark aggregator script. It groups performance by hardware and highlights the top-performing models.\n\n")
    
    for hw, records in hardware_data.items():
        output_mdx.append(f"## 💻 Hardware: {hw}\n")
        
        # Calculate best model by average TPS
        model_tps = defaultdict(list)
        for r in records:
            model_tps[r['model']].append(r['speed'])
            
        avg_tps = {m: sum(tps)/len(tps) for m, tps in model_tps.items()}
        if avg_tps:
            best_model = max(avg_tps, key=avg_tps.get)
            output_mdx.append(f"> 🏆 **Top Performing Model:** `{best_model}` (Avg Speed: **{avg_tps[best_model]:.2f} TPS**)\n\n")
            
        # Table Header
        output_mdx.append("| Model | Test | Think Mode | Speed (TPS) | TTFT (s) | Tokens | Time (s) |")
        output_mdx.append("|---|---|---|---|---|---|---|")
        
        # Sort records by model name, then test name
        records.sort(key=lambda x: (x['model'], x['test'], x['mode']))
        
        for r in records:
            output_mdx.append(f"| {r['model']} | {r['test']} | {r['mode']} | {r['speed']} | {r['ttft']} | {r['tokens']} | {r['time']} |")
            
        output_mdx.append("\n---\n\n")
        
    with open(readme_path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(output_mdx))
        
    print(f"✅ Successfully generated {readme_path}")

if __name__ == '__main__':
    generate_report()
